import { mkdir, readdir, writeFile } from "node:fs/promises";
import path from "node:path";

const projectRoot = process.cwd();
const musicDirectory = path.join(projectRoot, "public", "music");
const outputFile = path.join(projectRoot, "src", "generated", "music-tracks.ts");
const audioExtensions = new Set([".mp3", ".flac", ".m4a", ".ogg", ".wav", ".aac"]);
const coverExtensions = [".webp", ".jpg", ".jpeg", ".png", ".avif"];

function publicMusicPath(fileName) {
	return `/music/${encodeURIComponent(fileName)}`;
}

function parseTrackName(baseName) {
	const separator = baseName.match(/\s*[-－–—]\s*/);
	if (!separator || separator.index === undefined) return null;
	const artist = baseName.slice(0, separator.index).trim();
	const title = baseName.slice(separator.index + separator[0].length).trim();
	return artist && title ? { artist, title } : null;
}

let entries = [];
try {
	entries = await readdir(musicDirectory, { withFileTypes: true });
} catch (error) {
	if (error.code !== "ENOENT") throw error;
}

const files = entries.filter((entry) => entry.isFile()).map((entry) => entry.name);
const filesByLowerName = new Map(files.map((fileName) => [fileName.toLocaleLowerCase(), fileName]));
const tracks = [];

for (const fileName of files) {
	const extension = path.extname(fileName).toLocaleLowerCase();
	if (extension === ".ncm") {
		console.warn(`[music] Skipped encrypted NCM file: ${fileName}`);
		continue;
	}
	if (!audioExtensions.has(extension)) continue;

	const baseName = path.basename(fileName, extension);
	const metadata = parseTrackName(baseName);
	if (!metadata) {
		console.warn(`[music] Skipped file without "artist-title" naming: ${fileName}`);
		continue;
	}

	const lyricName = filesByLowerName.get(`${baseName}.lrc`.toLocaleLowerCase());
	const coverName = coverExtensions
		.map((coverExtension) => filesByLowerName.get(`${baseName}${coverExtension}`.toLocaleLowerCase()))
		.find(Boolean);

	tracks.push({
		id: baseName,
		title: metadata.title,
		artist: metadata.artist,
		audio: publicMusicPath(fileName),
		...(coverName ? { cover: publicMusicPath(coverName) } : {}),
		...(lyricName ? { lyric: publicMusicPath(lyricName) } : {}),
	});
}

tracks.sort((a, b) => a.id.localeCompare(b.id, "zh-CN"));

const source = `// Generated by scripts/generate-music-manifest.js. Do not edit manually.\nexport const generatedMusicTracks = ${JSON.stringify(tracks, null, "\t")} as const;\n`;
await mkdir(path.dirname(outputFile), { recursive: true });
await writeFile(outputFile, source, "utf8");
console.log(`[music] Generated ${tracks.length} track${tracks.length === 1 ? "" : "s"}.`);
